#!/usr/bin/env bash
# Configure a Wi-Fi connection with netplan.
#
# The password is read from the terminal without echo. It never appears in shell history, in the
# process list or in this repository. The result is /etc/netplan/60-wifi.yaml (root-only, mode 600).
#
# Usage (on the server, as a user with sudo):
#   WIFI_COUNTRY=CY ./setup-wifi.sh [interface]
#
#   interface      Wi-Fi interface, default: the first wl* interface (e.g. wlo1)
#   WIFI_COUNTRY   optional two-letter country code for the Wi-Fi regulatory domain. It unlocks the
#                  channels and transmit power allowed in your country (default: "world", the most
#                  restrictive set).
#   WIFI_REQUIRED  set to 1 if Wi-Fi is the main connection, so boot waits for it.
#                  Default: optional, a fallback next to Ethernet.
#
# Requires: wpasupplicant (sudo apt install wpasupplicant), python3 (preinstalled on Ubuntu).
set -euo pipefail

IFACE="${1:-$(ls /sys/class/net | grep -m1 '^wl' || true)}"
[[ -n "$IFACE" && -d "/sys/class/net/$IFACE" ]] || { echo "No Wi-Fi interface found" >&2; exit 1; }
dpkg -s wpasupplicant >/dev/null 2>&1 || { echo "Install wpasupplicant first: sudo apt install wpasupplicant" >&2; exit 1; }

read -rp  "Wi-Fi network name (SSID) for $IFACE: " SSID
read -rsp "Wi-Fi password: " PASS; echo
[[ ${#PASS} -ge 8 ]] || { echo "Password must be at least 8 characters" >&2; exit 1; }

TMP="$(mktemp)"; trap 'rm -f "$TMP"' EXIT
chmod 600 "$TMP"

# Build the YAML in Python. json.dumps() produces correctly escaped double-quoted strings, which are
# valid YAML, so quotes or backslashes in the SSID or password can't break the file. Values are
# passed through stdin, not argv, so they don't show up in the process list.
printf '%s\0%s\0%s\0%s\0%s' "$IFACE" "$SSID" "$PASS" "${WIFI_COUNTRY:-}" "${WIFI_REQUIRED:-0}" | python3 -c '
import sys, json
iface, ssid, password, country, required = sys.stdin.read().split("\0")
lines = [
    "# Wi-Fi connection. Generated by scripts/setup-wifi.sh. Contains a password: keep mode 600.",
    "network:",
    "  version: 2",
    "  wifis:",
    f"    {iface}:",
]
if country:
    lines.append(f"      regulatory-domain: {json.dumps(country.upper())}")
if required != "1":
    lines.append("      optional: true          # boot does not wait for Wi-Fi")
lines += [
    "      dhcp4: true",
    "      dhcp4-overrides:",
    "        route-metric: 600     # higher than Ethernet (100): the cable wins while plugged in",
    "      access-points:",
    f"        {json.dumps(ssid)}:",
    f"          password: {json.dumps(password)}",
]
print("\n".join(lines))
' > "$TMP"
unset PASS

sudo install -m 600 -o root -g root "$TMP" /etc/netplan/60-wifi.yaml
sudo netplan generate          # validates the config. Fails here, before anything changes, on a syntax error
sudo netplan apply
echo "Waiting for $IFACE to connect..."
for _ in $(seq 1 20); do
  if ip -4 -br addr show "$IFACE" | grep -q 'UP.*[0-9]\.[0-9]'; then
    ip -4 -br addr show "$IFACE"
    exit 0
  fi
  sleep 1
done
echo "No IPv4 address on $IFACE after 20s. Check: sudo journalctl -u netplan-wpa-$IFACE --since -5min" >&2
exit 1
